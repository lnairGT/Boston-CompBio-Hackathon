def score(a: str, b: str) -> int:
    """Substitution score for a residue pair; unknown characters score as 'X'."""
    v = BLOSUM62.get((a, b))
    if v is not None:
        return v
    return BLOSUM62.get(("X", b), BLOSUM62.get((a, "X"), BLOSUM62[("X", "X")]))
